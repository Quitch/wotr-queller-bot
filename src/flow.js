// J jump (grey box), P priority list (purple), T step (orange), N note/title.
// Node: [kind, x, y, width, height, text, extra]. extra: {items: [...], any: true (the items are alternatives),
//   bold: true (Elven Ring condition), t2: "non-bold part", wome: true (WoME only), die: "Army" (the die an action
//   box uses), name: "..." (a jump box's start point when it differs from its text)}.
// Edge: [from, to, label, waypoints, anchors {ex, en}, style ("elbow"), hideLabel]; slots 3-6 are filled from
//   anchors.json (generated by sync_anchors.py from the draw.io file: exact exit/entry anchors and waypoints per edge). A decision edge with no label is the answer the other edge lacks.
// Read nodes and edges through NODE / EDGE rather than by slot number.
import anchors from "./anchors.json" with { type: "json" };

export const NODE_KIND = {
  START: "S",
  ACTION: "A",
  DECISION: "D",
  FOLLOW_UP: "d",
  JUMP: "J",
  PRIORITY: "P",
  STEP: "T",
  NOTE: "N",
};
export const NODE_SLOT = {
  KIND: 0,
  X: 1,
  Y: 2,
  WIDTH: 3,
  HEIGHT: 4,
  TEXT: 5,
  EXTRA: 6,
};
export const EDGE_SLOT = {
  FROM: 0,
  TO: 1,
  LABEL: 2,
  WAYPOINTS: 3,
  ANCHORS: 4,
  STYLE: 5,
  HIDE_LABEL: 6,
};
export const NODE = {
  kind: (node) => node[NODE_SLOT.KIND],
  text: (node) => node[NODE_SLOT.TEXT],
  extra: (node) => node[NODE_SLOT.EXTRA] || {},
  box: (node) => ({
    x: node[NODE_SLOT.X],
    y: node[NODE_SLOT.Y],
    width: node[NODE_SLOT.WIDTH],
    height: node[NODE_SLOT.HEIGHT],
  }),
};
export const EDGE = {
  from: (edge) => edge[EDGE_SLOT.FROM],
  to: (edge) => edge[EDGE_SLOT.TO],
  label: (edge) => edge[EDGE_SLOT.LABEL],
  waypoints: (edge) => edge[EDGE_SLOT.WAYPOINTS],
  anchors: (edge) => edge[EDGE_SLOT.ANCHORS],
  isElbow: (edge) => edge[EDGE_SLOT.STYLE] === "elbow",
  hidesLabel: (edge) => !!edge[EDGE_SLOT.HIDE_LABEL],
};
export const FLOW = {};
function page(name, short, nodes, edges) {
  FLOW[short] = { name, nodes, edges };
}

