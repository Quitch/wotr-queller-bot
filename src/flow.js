// Arrow routing from the draw.io file: the anchors, waypoints and style of each edge, matched by its ends and label.
for (const record of anchors) {
  const edge = FLOW[record.p].edges.find(
    (candidate) =>
      candidate[EDGE_SLOT.FROM] === record.f &&
      candidate[EDGE_SLOT.TO] === record.t &&
      (candidate[EDGE_SLOT.LABEL] || null) === (record.l || null),
  );
  if (!edge) continue;
  edge[EDGE_SLOT.WAYPOINTS] = record.wp || edge[EDGE_SLOT.WAYPOINTS] || null;
  if (record.an)
    edge[EDGE_SLOT.ANCHORS] = Object.assign(
      {},
      edge[EDGE_SLOT.ANCHORS] || {},
      record.an,
    );
  if (record.elbow) edge[EDGE_SLOT.STYLE] = "elbow";
  if (record.nolabel) edge[EDGE_SLOT.HIDE_LABEL] = true;
}
